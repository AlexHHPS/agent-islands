// Builds ui/icons.js, so the app ships its icons locally (the page CSP allows no CDN).
// Interface icons come from the pinned Lucide package (ISC). Vendor marks are monochrome SVGs kept in
// assets/brands/ (fill="currentColor"); the app tints each one with its --brand-<id> colour from tokens.css,
// so every mark can be recoloured in one place. Run: node scripts/icons.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

// One semantic name per concept. The same idea always uses the same glyph across the app.
const ui = {
  // Navigation and structure
  island: null, // Agent Islands' own island mark, kept from the original set (product metaphor, not a library glyph).
  terminal: 'square-terminal', tiles: 'layout-grid', sidebar: 'panel-left', search: 'search', settings: 'settings',
  back: 'chevron-left', arrow: 'chevron-right', chevron: 'chevron-down', popup: 'chevrons-up-down', up: 'corner-left-up', down: 'arrow-down',
  expand: 'maximize-2', external: 'external-link', dots: 'ellipsis', filter: 'list-filter', sliders: 'sliders-horizontal',
  // Actions
  plus: 'plus', close: 'x', check: 'check', refresh: 'refresh-cw', reload: 'rotate-cw', send: 'arrow-up', save: 'save',
  trash: 'trash-2', pencil: 'pencil', pin: 'pin', link: 'link', history: 'history', returnKey: 'corner-down-left',
  play: 'play', pause: 'pause', stop: 'square', record: 'circle-dot', mic: 'mic', volume: 'volume-2', bell: 'bell',
  folder: 'folder', folderPlus: 'folder-plus', file: 'file-text', lock: 'lock', shield: 'shield-off', globe: 'globe',
  // Agent states (agent-state.js) and modes
  working: 'loader-circle', plan: 'list-todo', goal: 'target', work: 'hammer', question: 'message-circle-question',
  attention: 'circle-alert', error: 'circle-x', complete: 'circle-check', paused: 'circle-pause', idle: 'circle-dashed',
  eye: 'eye', eyeOff: 'eye-off', bot: 'bot', pulse: 'activity', checkpoint: 'bookmark', docker: 'container',
  // Tools and settings
  qa: 'clipboard-check', plug: 'plug', users: 'users', wave: 'radio', spark: 'sparkles', help: 'circle-help', info: 'info', leaf: 'leaf',
  // Browser and annotations
  launcher: 'message-square-plus', pointer: 'mouse-pointer-2', text: 'type', camera: 'camera', list: 'list',
  desktop: 'monitor', laptop: 'laptop', tablet: 'tablet', mobile: 'smartphone',
};
// Old names still used in code map onto the semantic ones above.
const aliases = { gear: 'settings', terminalPlus: 'plus' };
const island = '<path d="m3 16 5-4 4 1 4-5 5 7-7 5H7ZM8 12V7m-2 2 2-4 2 4"/>';

// Vendor marks: the files in assets/brands/, named by harness id.
const brands = {
  claude: 'Claude Code', codex: 'Codex', gemini: 'Gemini CLI', opencode: 'OpenCode', goose: 'Goose', hermes: 'Hermes Agent', docker: 'Docker',
};

const lucideDir = 'node_modules/lucide-static/icons/';
const inner = svg => svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
const icons = { island };
for (const [name, lucide] of Object.entries(ui)) {
  if (!lucide) continue;
  const file = lucideDir + lucide + '.svg';
  if (!existsSync(file)) throw new Error(`Lucide has no icon "${lucide}" for "${name}"`);
  icons[name] = inner(readFileSync(file, 'utf8'));
}
for (const [alias, target] of Object.entries(aliases)) icons[alias] = icons[target];

const brandOut = {};
for (const [id, name] of Object.entries(brands)) {
  const file = `assets/brands/${id}.svg`;
  if (!existsSync(file)) throw new Error(`Missing brand mark ${file}`);
  const svg = readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '').replace(/\s*\n\s*/g, '').trim()
    .replace('<svg', `<svg class="brand-logo brand-${id}" aria-hidden="true" focusable="false"`);
  if (/fill="#|url\(/.test(svg)) throw new Error(`${file} must be monochrome (currentColor) so the app can tint it`);
  brandOut[id] = { name, svg };
}

// License texts travel with the vendored files (THIRD_PARTY_NOTICES.md links them).
writeFileSync('ui/vendor/lucide-LICENSE', readFileSync('node_modules/lucide-static/LICENSE', 'utf8'));
const lucideVersion = JSON.parse(readFileSync('node_modules/lucide-static/package.json', 'utf8')).version;
writeFileSync('ui/icons.js', `'use strict';
// Generated by scripts/icons.mjs. Do not edit by hand.
// Interface icons: lucide-static@${lucideVersion} (ISC). Vendor marks: assets/brands/*.svg, tinted by --brand-<id>.
// Product names and logos belong to their owners and identify the tool a terminal runs.
const ICONS=${JSON.stringify(icons)};
const BRANDS=${JSON.stringify(brandOut)};
// Decorative by default: the button or row around it carries the accessible name.
function icon(name){return '<svg class="icon" viewBox="0 0 24 24" aria-hidden="true">'+(ICONS[name]||ICONS.bot)+'</svg>'}
// The official mark of the harness a terminal runs; a terminal glyph for a plain shell and a bot for the rest.
function harnessLogo(harness){
  const b=BRANDS[harness];
  if(!b)return icon(harness==='shell'||harness==='custom'?'terminal':'bot');
  return b.svg;
}
function harnessName(harness){return BRANDS[harness]?.name||harness}
`);
console.log(`PASS icons: ${Object.keys(icons).length} interface icons, ${Object.keys(brandOut).length} vendor marks`);

import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1512,height:960}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{window.messages=[];window.webkit={messageHandlers:{native:{postMessage:m=>messages.push(m)}}}});
 await page.goto(pathToFileURL(resolve('ui/index.html')).href);
 await page.evaluate(()=>receiveNative({event:'snapshot',data:{native:true,projects:[{id:'p',name:'Workshop',path:'/tmp'}],agents:[{id:'one',projectId:'p',name:'Codex',harness:'codex',managed:true,processRunning:true,state:'active',mode:'work'},{id:'two',projectId:'p',name:'Claude',harness:'claude',managed:true,processRunning:true,state:'ready',mode:'plan'},{id:'goal',projectId:'p',name:'Goal',harness:'codex',managed:false,state:'observed',mode:'goal',goalStatus:'blocked',goalObjective:'Restaurar la integración',threadId:'01900000-0000-7000-8000-000000000001'}],binaries:{codex:'/bin/codex',claude:'/bin/claude'},docker:{containers:[]}}}));
 await page.evaluate(()=>selectAgent('one'));
 await page.locator('#prompt').fill('Conserva este borrador');
 await page.evaluate(()=>selectAgent('two'));
 await page.locator('#prompt').fill('Otro encargo');
 await page.evaluate(()=>receiveNative({event:'attachment',data:{owner:'one',id:'image-1',name:'Captura',preview:'data:image/png;base64,iVBORw0KGgo='}}));
 assert.equal(await page.locator('.composer-image').count(),0,'Asynchronous image must retain its destination');
 await page.evaluate(()=>selectAgent('one'));
 assert.equal(await page.locator('#prompt').inputValue(),'Conserva este borrador');
 assert.equal(await page.locator('.composer-image').count(),1);
 await page.evaluate(()=>{const p=document.querySelector('#prompt');p.setSelectionRange(9,13);toggleDictation();receiveNative({event:'dictation',data:{recording:true,text:'nuevo'}})});
 assert.equal(await page.locator('#prompt').inputValue(),'Conserva nuevo borrador','Dictation replaces selected text and preserves surrounding draft');
 await page.evaluate(()=>receiveNative({event:'dictation',data:{recording:false}}));
 await page.evaluate(()=>receiveNative({event:'skills',data:{skills:[{name:'atelier',description:'Diseñar y verificar interfaces'}]}}));
 await page.locator('#prompt').fill('$at');await page.locator('#prompt').press('Tab');
 assert.equal(await page.locator('#prompt').inputValue(),'$atelier ');
 await page.locator('#prompt').fill('/borrar');await page.locator('#prompt').press('Meta+Enter');
 assert.equal(await page.locator('#prompt').inputValue(),'');assert.equal(await page.locator('.composer-image').count(),0);
 assert(await page.evaluate(()=>messages.some(m=>m.action==='removeAttachment'&&m.attachmentId==='image-1')));
 await page.locator('#prompt').fill('/resumen');await page.locator('#prompt').press('Meta+Enter');
 assert(await page.evaluate(()=>messages.some(m=>m.action==='intelligence'&&m.kind==='recap')));
 assert.equal(await page.evaluate(()=>messages.filter(m=>m.action==='prompt').length),0,'Commands must not send agent turns');
 await page.evaluate(()=>receiveNative({event:'intelligenceResult',data:{requestId:aiRequestID,error:'Servidor de resúmenes desconectado'}}));
 assert(await page.locator('#ai-retry').isVisible());
 await page.evaluate(()=>selectAgent('goal'));
 assert((await page.locator('#external-notice').textContent()).includes('Restaurar la integración'));
 await page.locator('#analyze-goal').click();
 assert(await page.evaluate(()=>messages.some(m=>m.action==='intelligence'&&m.id==='goal'&&m.kind==='unblock')));
 assert(await page.locator('.agent-chip.signal-blocked').count()>0);
 assert.deepEqual(errors,[]);
 console.log('PASS interactions: independent AI, failed connection/retry, actionable external goal, skills, draft isolation, asynchronous images, dictation insertion and erase command');
}finally{await browser.close()}
